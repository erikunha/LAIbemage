/**
 * Report-tuple resolution through the 002 store: spec 003, task 5.2.
 *
 * ## What this test protects
 *
 * The runner carries the reproduction tuple verbatim into the report artifact
 * (`runner.test.ts` proves the round-trip against a literal). This file proves
 * the step AFTER that: the tuple a real report carries resolves through the
 * 002 store lookup API back onto the snapshot that pins the split the run
 * scored, the spot-check task 5.2 asks for ("any metric can be traced back to
 * the exact data it was computed on", `DatasetSnapshot` contract).
 *
 * It fails when any of these regress:
 *  - the runner stops carrying a tuple field verbatim into `report.json`
 *    (a redacted or transformed `snapshotId` silently stops resolving);
 *  - `assertReproductionTuple` narrows the accepted `snapshotId` values (e.g.
 *    to git-sha shape), refusing store-backed runs;
 *  - the store's snapshot lookup keys (`getById`, `findByManifestHash`)
 *    change shape or stop matching the values the artifact carries.
 *
 * ## The recorded pinning convention (task 5.2)
 *
 * A snapshot that pins a benchmark gold split records, per the 002 contract's
 * own semantics (`snapshot.ts`: `manifestHash` pins the manifest,
 * `splitAssignments` pins the split assignment):
 *  - `manifestHash`     = the SplitManifest's `manifestHash`: the identity of
 *                         the split file, which is exactly what the
 *                         reproduction tuple carries as `splitFingerprint`
 *                         (`splits.ts` header);
 *  - `splitAssignments` = the partition fingerprint of the manifest's
 *                         assignments (sha256 over the sorted `id -> split`
 *                         pairs, `computePartitionFingerprint`).
 *
 * The CLI's standalone default (git HEAD as the snapshot id) is a CODE
 * snapshot, not a store row, and stays untouched: this test covers the
 * store-backed shape, where the caller passes the store snapshot id.
 */

import { mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { captureEnv, runBenchmark } from '../../src/benchmark/runner.js';
import {
  computePartitionFingerprint,
  generateSplitManifest,
  type SplitItem,
} from '../../src/benchmark/splits.js';
import type { GoldItem, PredictionItem } from '../../src/benchmark/metrics.js';
import {
  createTestStore,
  ontologyFixture,
  snapshotFixture,
  type TestStore,
} from '../store/helpers.js';

/** Items shaped like the runner suite's fixture: two classes, both anomalies. */
function makeItems(count: number): SplitItem[] {
  const items: SplitItem[] = [];
  for (let index = 0; index < count; index += 1) {
    const id = `img-${String(index).padStart(3, '0')}`;
    items.push({
      id,
      class: `class-${index % 2}`,
      anomaly: index % 3 === 0 ? 'normal' : 'anomalous',
      group: `group-${index % 4}`,
      sha256: `hash-${id}`,
      path: `img/${id}.jpg`,
    });
  }
  return items;
}

/** Gold derived from the manifest the way the CLI derives it (`labelKeyOf`). */
function goldFromAssignments(
  assignments: readonly { id: string; class: string; anomaly: 'normal' | 'anomalous' }[],
): GoldItem[] {
  return assignments.map((assignment) => ({
    id: assignment.id,
    labelKey:
      assignment.anomaly === 'normal' ? 'normal' : `defect:${assignment.class}`,
  }));
}

/** Predictions that are correct for the first `correctCount` gold items. */
function predictionsFrom(gold: GoldItem[], correctCount: number): PredictionItem[] {
  return gold.map((item, index) => ({
    id: item.id,
    labelKey: index < correctCount ? item.labelKey : 'defect:wrong',
    probability: index < correctCount ? 0.9 : 0.2,
    latencyMs: 100 + index,
    costUsd: 0.001,
  }));
}

describe('report tuple resolution through the 002 store', () => {
  let store: TestStore;
  let outputDir: string;

  beforeEach(async () => {
    store = await createTestStore();
    outputDir = mkdtempSync(path.join(tmpdir(), 'vision-lens-report-tuple-'));
  });

  afterEach(() => {
    store.cleanup();
    rmSync(outputDir, { recursive: true, force: true });
  });

  it("resolves a real report's tuple onto the snapshot pinning the scored split", async () => {
    // 1. A real gold split, generated by the same code make-splits uses.
    const manifest = generateSplitManifest({
      id: 'resolution-fixture.gold',
      datasetId: 'resolution-fixture',
      seed: 42,
      items: makeItems(12),
    });

    // 2. A real store snapshot pinning that split (002 lookup surface).
    const ontology = store.repos.ontology.insert(ontologyFixture());
    const snapshot = store.repos.snapshots.insert(
      snapshotFixture({
        manifestHash: manifest.manifestHash,
        splitAssignments: manifest.partitionFingerprint ?? computePartitionFingerprint(manifest.assignments),
        ontologyVersionId: ontology.id,
      }),
    );

    // 3. The real runner, scoring against that manifest with the integrity
    //    gate on and every item's bytes verified against the manifest.
    const gold = goldFromAssignments(manifest.assignments);
    const result = await runBenchmark({
      suite: 'resolution-fixture',
      model: 'demo',
      gold,
      predictions: predictionsFrom(gold, 8),
      tuple: {
        snapshotId: snapshot.id,
        splitFingerprint: manifest.manifestHash,
        modelVersion: 'model:demo@1.0.0',
        configFingerprint: 'fp2:0123456789abcdef',
        env: captureEnv(),
      },
      splitManifest: manifest,
      assetHashes: new Map(manifest.assignments.map((a) => [a.id, a.sha256])),
      minSamples: 1,
      outputDir,
      now: new Date('2026-01-01T00:00:00.000Z'),
    });

    // 4. The artifact as written to disk; the spot-check reads the report,
    //    not the in-memory result.
    const report = JSON.parse(readFileSync(result.reportJsonPath, 'utf8')) as {
      tuple: { snapshotId: string; splitFingerprint: string };
    };

    // 5. Resolution through the store's own lookups: both tuple fields that
    //    name the data land on the SAME snapshot row.
    const byId = store.repos.snapshots.getById(report.tuple.snapshotId);
    expect(byId?.id).toBe(snapshot.id);

    const byManifestHash = store.repos.snapshots.findByManifestHash(
      report.tuple.splitFingerprint,
    );
    expect(byManifestHash?.id).toBe(snapshot.id);

    // 6. Content: the resolved snapshot pins the partition of the very
    //    assignments that were scored, recomputed here, not taken from the
    //    generator's bookkeeping.
    expect(byId?.splitAssignments).toBe(
      computePartitionFingerprint(manifest.assignments),
    );
  });
});
