"""The golden transcript: a recorded scripted session.

The file session.jsonl beside this module holds the worker frames of one
scripted session: handshake, one malformed-line error case, then one embed
request driven to its result. Regenerating the transcript must reproduce the
file byte for byte; any divergence is a protocol change.

Command line:

- python -m visionlens.golden            check the packaged file (exit 1 on drift)
- python -m visionlens.golden --regen    rewrite the packaged file
- python -m visionlens.golden --print    print the transcript to stdout
"""

from __future__ import annotations

import argparse
import io
import sys
from pathlib import Path
from typing import Sequence

from ..worker import Worker

GOLDEN_FILE_NAME = "session.jsonl"

#: The scripted host side of the recorded session, in order. The malformed
#: line sits before the embed request so the reader answers it before any
#: operation thread exists, which keeps the recorded ordering deterministic.
SCRIPT: tuple[bytes, ...] = (
    b'{"protocol":"visionlens.worker.v1","kind":"hello","protocolVersion":"1.0.0","contractVersion":"1.0.0"}',
    b"{not json",
    b'{"protocol":"visionlens.worker.v1","kind":"request","requestId":"r-1","operation":"vision.embed","contractVersion":"1.0.0","workspaceId":"ws-golden","params":{"images":["golden-alpha","golden-beta"],"model":"siglip2-base","device":"cpu"},"budget":{"maxSeconds":60,"maxUsdMicro":0}}',
)


def golden_path() -> Path:
    """Return the path of the packaged golden transcript."""
    return Path(__file__).with_name(GOLDEN_FILE_NAME)


def read_golden() -> bytes:
    """Return the recorded transcript bytes."""
    return golden_path().read_bytes()


def build_transcript() -> bytes:
    """Replay the scripted session through a real worker loop.

    The worker runs over two in-memory streams, the same loop the subprocess
    entry point runs; only the transport differs.
    """
    reader = io.BytesIO(b"".join(line + b"\n" for line in SCRIPT))
    writer = io.BytesIO()
    worker = Worker(reader=reader, writer=writer)
    worker.run()
    return writer.getvalue()


def check(path: Path | None = None) -> int:
    """Compare the regenerated transcript with the recorded file."""
    target = path if path is not None else golden_path()
    recorded = target.read_bytes()
    regenerated = build_transcript()
    if recorded == regenerated:
        sys.stderr.write("golden transcript matches: " + str(target) + "\n")
        return 0
    sys.stderr.write("golden transcript drifted from: " + str(target) + "\n")
    sys.stderr.write("recorded bytes: " + str(len(recorded)) + "\n")
    sys.stderr.write("regenerated bytes: " + str(len(regenerated)) + "\n")
    return 1


def regen(path: Path | None = None) -> int:
    """Rewrite the golden file from a fresh replay."""
    target = path if path is not None else golden_path()
    target.write_bytes(build_transcript())
    sys.stderr.write("golden transcript regenerated: " + str(target) + "\n")
    return 0


def main(argv: Sequence[str] | None = None) -> int:
    """Entry point of python -m visionlens.golden."""
    parser = argparse.ArgumentParser(
        prog="visionlens.golden",
        description="Check or regenerate the golden worker transcript.",
    )
    parser.add_argument("--check", action="store_true", help="check the golden file (default)")
    parser.add_argument("--regen", action="store_true", help="rewrite the golden file")
    parser.add_argument("--print", dest="print_transcript", action="store_true",
                        help="print the transcript to stdout")
    parser.add_argument("path", nargs="?", default=None, help="target file (default: packaged file)")
    args = parser.parse_args(argv)
    target = Path(args.path) if args.path else None
    if args.print_transcript:
        sys.stdout.buffer.write(build_transcript())
        return 0
    if args.regen:
        return regen(target)
    return check(target)


if __name__ == "__main__":
    sys.exit(main())
